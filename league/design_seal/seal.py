"""P2 design-seal core: dev-era season filtering for EDA / reliability artefacts.

Design rule (AUDIT.md section 6, proposal P2; IMPROVEMENT_PROGRAM.md):
EDA and reliability artefacts may only be computed on DEV-ERA seasons.
Sealed-season aggregates are generated by the coordinator after the
design document freezes, and are never shown to builders.

This module is the shared filter every EDA generator wraps. It is
dependency-free (the project venv has no PyYAML): league ``config.yaml``
files are read with a small targeted parser for the season fields only.

A league's sealed seasons are, in precedence order:
  1. ``virgin_primary`` + ``virgin_confirmatory`` in config.yaml
     (a plain ``virgin:`` key is also honoured);
  2. otherwise, any season in the config ``seasons:`` list that is not
     in ``dev_seed`` / ``dev_period`` / ``dev_seasons``.

Everything else in the config's season list is dev-era (seed + scored
dev folds). Rows / artefacts whose season is sealed must never enter
an EDA or reliability table.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

_SEASON_RE = re.compile(r"^\d{4}(?:[/\- ]\d{2,4})?(?:\s*-\s*\w+)?$")
# A sealed-season candidate from a virgin_* config key must look like a
# season label: "2025", "2025/2026", "2026 - Apertura". This rejects
# counts ("110"), status labels ("2026/2027-complete", "2026 transitional")
# that ride along on virgin_* metadata keys.
_SEALED_VALUE_RE = re.compile(r"^\d{4}(?:/\d{2,4})?(?: - .+)?$")


class SealViolation(AssertionError):
    """Raised when sealed-season data is found where only dev-era data may be."""


def _strip_comment(value: str) -> str:
    # Remove an inline "  # comment" that follows the value.
    if " #" in value:
        value = value.split(" #", 1)[0]
    return value.strip()


def _unquote(value: str) -> str:
    value = _strip_comment(value)
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def parse_config_seasons(config_path: Path) -> dict:
    """Extract season fields from a league config.yaml without PyYAML."""
    text = Path(config_path).read_text(encoding="utf-8", errors="replace")
    out: dict = {"seasons": [], "dev": [], "sealed": [], "sealed_key_seen": False}
    list_keys = {
        "seasons": "seasons",
        "dev_seed": "dev",
        "dev_period": "dev",
        "dev_seasons": "dev",
        "dev_seasons_loaded": "dev",
    }
    null_tokens = {"", "null", "none", "~"}
    # Any virgin_* key names a sealed season, except metadata keys that
    # describe the virgin window without naming its season.
    non_season_virgin_keys = {"virgin_n", "virgin_status"}

    def parse_flow_list(raw: str):
        inner = raw[raw.index("[") + 1 : raw.rindex("]")]
        return [_unquote(v) for v in inner.split(",") if v.strip()]

    in_virgin_block = False
    for line in text.splitlines():
        m = re.match(r"^([A-Za-z_]+):\s*(.*)$", line)
        if not m:
            # Indented keys: only virgin-season keys are honoured when
            # nested (some configs nest them under a section), plus the
            # `season:` line inside a top-level `virgin:` block.
            mi = re.match(r"^\s+([A-Za-z_]+):\s*(.*)$", line)
            if mi:
                ikey, iraw = mi.group(1), mi.group(2)
                if in_virgin_block and ikey == "season":
                    val = _unquote(iraw)
                    if val.lower() not in null_tokens:
                        out["sealed"].append(val)
                    continue
                if (ikey == "virgin" or ikey.startswith("virgin_")) and ikey not in non_season_virgin_keys:
                    out["sealed_key_seen"] = True
                    if "[" in iraw and "]" in iraw:
                        out["sealed"].extend(
                            v for v in parse_flow_list(iraw) if v.lower() not in null_tokens)
                    else:
                        val = _unquote(iraw)
                        if val.lower() not in null_tokens:
                            out["sealed"].append(val)
            continue
        key, raw = m.group(1), m.group(2)
        in_virgin_block = key == "virgin" and not _strip_comment(raw)
        if key in list_keys:
            if "[" in raw and "]" in raw:
                vals = parse_flow_list(raw)
                out[list_keys[key]].extend(v for v in vals if v.lower() not in null_tokens)
        elif (key == "virgin" or key.startswith("virgin_")) and key not in non_season_virgin_keys:
            out["sealed_key_seen"] = True
            if "[" in raw and "]" in raw:
                out["sealed"].extend(
                    v for v in parse_flow_list(raw) if v.lower() not in null_tokens)
            else:
                val = _unquote(raw)
                if val.lower() not in null_tokens:
                    out["sealed"].append(val)
    return out


@dataclass
class Seal:
    """The dev/sealed season partition for one league."""

    league: str
    dev_seasons: list = field(default_factory=list)    # seed + scored dev folds
    sealed_seasons: list = field(default_factory=list)  # virgin primary (+ confirmatory)

    @property
    def sealed(self) -> set:
        return set(self.sealed_seasons)

    def is_sealed(self, season) -> bool:
        return str(season) in self.sealed

    def is_dev(self, season) -> bool:
        return str(season) in set(self.dev_seasons)


def load_seal(league_dir) -> Seal:
    """Build the Seal for a league directory from its config.yaml."""
    league_dir = Path(league_dir)
    cfg = league_dir / "config.yaml"
    if not cfg.exists():
        raise FileNotFoundError(f"no config.yaml in {league_dir}")
    parsed = parse_config_seasons(cfg)
    sealed = [s for s in dict.fromkeys(parsed["sealed"]) if _SEALED_VALUE_RE.match(s)]
    dev = list(dict.fromkeys(parsed["dev"]))
    if not sealed and not parsed["sealed_key_seen"] and parsed["seasons"] and dev:
        # Fallback (no virgin key at all): any listed season outside the
        # dev era is sealed. Never applied when a virgin key exists but
        # is explicitly null/none — that league has no sealed window.
        sealed = [s for s in parsed["seasons"] if s not in dev]
    if not dev and parsed["seasons"]:
        dev = [s for s in parsed["seasons"] if s not in sealed]
    return Seal(league=league_dir.name, dev_seasons=dev, sealed_seasons=sealed)


# --------------------------------------------------------------------------
# Row filtering (the wrapper an EDA generator uses)
# --------------------------------------------------------------------------

def filter_rows(rows, seal: Seal, season_key: str = "season"):
    """Return only dev-era rows. Sealed-season rows are dropped, never kept.

    ``rows`` is any iterable of mappings carrying a season under
    ``season_key``. Rows with a missing/unknown season are dropped too:
    an EDA table must be provably dev-only, so unlabelled rows do not pass.
    """
    kept = []
    for row in rows:
        season = row.get(season_key) if hasattr(row, "get") else None
        if season is None:
            continue
        if seal.is_sealed(season):
            continue
        if seal.dev_seasons and not seal.is_dev(season):
            continue
        kept.append(row)
    return kept


def count_sealed_rows(rows, seal: Seal, season_key: str = "season") -> int:
    return sum(1 for r in rows if hasattr(r, "get") and seal.is_sealed(r.get(season_key)))


# --------------------------------------------------------------------------
# Artefact checking (JSON-like structures and plain text)
# --------------------------------------------------------------------------

def find_sealed_references(obj, seal: Seal, path: str = "$"):
    """Recursively find sealed-season references in a JSON-like object.

    Returns a list of (path, season, kind) where kind is 'key' (a mapping
    key equal to a sealed season — the signature of a per-season aggregate
    table that includes the sealed season) or 'value'.
    """
    hits = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            if str(k) in seal.sealed:
                hits.append((f"{path}.{k}", str(k), "key"))
            hits.extend(find_sealed_references(v, seal, f"{path}.{k}"))
    elif isinstance(obj, (list, tuple)):
        for i, v in enumerate(obj):
            hits.extend(find_sealed_references(v, seal, f"{path}[{i}]"))
    elif isinstance(obj, str):
        if obj in seal.sealed:
            hits.append((path, obj, "value"))
    return hits


def assert_dev_only(obj, seal: Seal, what: str = "artefact") -> None:
    """Fail loudly if a would-be EDA/reliability artefact contains sealed data."""
    hits = find_sealed_references(obj, seal)
    if hits:
        detail = "; ".join(f"{p} -> {s} ({k})" for p, s, k in hits[:10])
        raise SealViolation(
            f"{what} for {seal.league} contains sealed-season data: {detail}"
        )


def text_mentions_sealed(text: str, seal: Seal):
    """Return [(season, line_number, line)] for lines naming a sealed season."""
    out = []
    for i, line in enumerate(text.splitlines(), start=1):
        for season in seal.sealed_seasons:
            if season and season in line:
                out.append((season, i, line.strip()))
    return out
